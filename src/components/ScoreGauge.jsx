import React from 'react';
import TierBadge from './TierBadge';
import { HelpCircle, Info } from 'lucide-react';

export default function ScoreGauge({
  score = 0,
  defaultProbability = 0,
  tier = 'Watch',
  label = 'MEDIUM',
  thinFile = false,
  msmeId = '',
}) {
  // Convert default_probability to percentage with 1 decimal place
  const pdPercentage = (defaultProbability * 100).toFixed(1);

  // SVG Gauge calculations for a 180-degree semi-circle arc
  // Radius = 80, Center = (100, 90)
  const radius = 70;
  const strokeWidth = 14;
  const cx = 100;
  const cy = 90;

  // Arc length for semi-circle (PI * R)
  const arcLength = Math.PI * radius;
  // Score percentage fill (0 to 100 mapped to 0 to arcLength)
  const fillDashoffset = arcLength - (score / 100) * arcLength;

  // Gauge color based on score zones
  const getGaugeColor = (scoreVal) => {
    if (scoreVal >= 95) return '#16A34A'; // Green (Healthy)
    if (scoreVal >= 90) return '#F59E0B'; // Amber (Watch)
    if (scoreVal >= 80) return '#EA580C'; // Orange (Stressed)
    return '#DC2626';                     // Red (High risk)
  };

  const gaugeColor = getGaugeColor(score);

  return (
    <div className="bg-white rounded-xl border border-slate-200 p-6 shadow-sm flex flex-col items-center relative overflow-hidden">
      {/* Header with MSME ID if provided */}
      {msmeId && (
        <div className="w-full flex items-center justify-between pb-3 mb-2 border-b border-slate-100 text-xs text-slate-500">
          <span className="font-medium text-slate-700">Business ID: <code className="bg-slate-100 px-1.5 py-0.5 rounded text-slate-900 font-mono">{msmeId}</code></span>
          <span className="text-[11px] text-slate-400">Score generated by Vridhi AI</span>
        </div>
      )}

      {/* Semicircle Gauge Visualization */}
      <div className="relative w-56 h-32 flex items-center justify-center mt-2">
        <svg viewBox="0 0 200 115" className="w-full h-full overflow-visible">
          {/* Background Arc (Gray) */}
          <path
            d="M 30 90 A 70 70 0 0 1 170 90"
            fill="none"
            stroke="#E2E8F0"
            strokeWidth={strokeWidth}
            strokeLinecap="round"
          />

          {/* Color Zone Indications (Subtle Track Guides) */}
          <path
            d="M 30 90 A 70 70 0 0 1 170 90"
            fill="none"
            stroke={gaugeColor}
            strokeWidth={strokeWidth}
            strokeDasharray={arcLength}
            strokeDashoffset={fillDashoffset}
            strokeLinecap="round"
            className="transition-all duration-700 ease-out"
          />

          {/* Score Text in Center */}
          <text x="100" y="75" textAnchor="middle" className="fill-slate-900 text-4xl font-extrabold tracking-tight">
            {score}
          </text>
          <text x="100" y="93" textAnchor="middle" className="fill-slate-400 text-[11px] font-semibold tracking-wider uppercase">
            Risk Score
          </text>
        </svg>
      </div>

      {/* Risk Tier & Default Probability Display */}
      <div className="w-full mt-4 bg-slate-50 rounded-lg p-3 border border-slate-100 flex flex-col sm:flex-row items-center justify-between gap-3">
        {/* Default Probability (Primary Metric) */}
        <div className="text-center sm:text-left">
          <div className="text-[11px] font-semibold text-slate-500 uppercase tracking-wider">Default Probability</div>
          <div className="text-2xl font-black text-slate-900">
            {pdPercentage}%
          </div>
        </div>

        {/* Tier & Label Badge */}
        <div className="flex flex-col items-center sm:items-end gap-1">
          <span className="text-[11px] font-semibold text-slate-500 uppercase tracking-wider">Risk Tier</span>
          <TierBadge tier={tier} label={label} />
        </div>
      </div>

      {/* Thin File Badge & Notice */}
      {thinFile && (
        <div className="w-full mt-3 bg-teal-50 border border-teal-200 rounded-lg p-2.5 flex items-start gap-2 text-xs text-teal-900">
          <Info className="w-4 h-4 text-teal-600 flex-shrink-0 mt-0.5" />
          <div>
            <span className="font-bold text-teal-950">No bureau history</span>
            <p className="text-[11px] text-teal-800 leading-snug mt-0.5">
              Traditional lenders would decline this business by default. Vridhi AI scores it on alternative data.
            </p>
          </div>
        </div>
      )}
    </div>
  );
}
